fun getAppStrings(languageCode: String?): AppStrings {
    return when (languageCode?.lowercase()) {
        "bn" -> BnStrings
        "hi" -> HiStrings
        else -> EnStrings
    }
}

val LocalAppStrings = staticCompositionLocalOf { EnStrings }

@Composable
fun appStrings(): AppStrings = LocalAppStrings.current
